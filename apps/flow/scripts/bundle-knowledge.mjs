#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(import.meta.dirname, "../../..");

const sources = [
  ".agents/flow/flow.md",
  ".agents/flow/README.md",
  "docs/readme.md",
  "ARCHITECTURE.md",
  "AGENTS.md",
  ".agents/flow/operations/context.md",
  ".agents/flow/operations/verification.md",
  ".agents/flow/operations/skills.md",
  ".agents/flow/operations/worktrees.md",
  "PRODUCT.md",
];

const sections = sources.map((relative) => {
  const absolute = path.join(repoRoot, relative);
  const content = readFileSync(absolute, "utf-8");
  return {
    content,
    id: relative.replaceAll(/[^\w]+/gu, "_"),
    path: relative,
  };
});

const out = `/* generated by apps/flow/scripts/bundle-knowledge.mjs — do not edit */
export const flowKnowledgeSections = ${JSON.stringify(sections, null, 2)} as const;

export type FlowKnowledgeSectionId =
  (typeof flowKnowledgeSections)[number]["id"];
`;

writeFileSync(
  path.join(repoRoot, "apps/flow/app/_lib/flow-agent/knowledge-snapshot.ts"),
  out,
  "utf-8"
);

console.log(`Bundled ${sections.length} knowledge sections.`);
